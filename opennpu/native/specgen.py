"""Derive a fused-decode model spec (MLIR-AIR superkernel) from a Hugging Face config.json.

The MLIR-AIR fused decode engine describes a model by ~20 numbers: a C++ header for the kernels
and a Python entry for the host driver. Upstream writes both by hand per model. This module
derives them from config.json using the same rules the hand-written entries follow, and checks
every hardware constraint up front so an unsupported shape fails here, not as a wedged NPU.

Rules (verified against every upstream entry: llama-3.2-1b/3b, llama-3.1-8b, qwen3-4b/8b,
qwen2.5-3b/7b, phi4-mini):
  ROW_BLOCK=32 rows, COL_BLOCK=256 cols, 16 projection cores, PAYLOAD=512.
  PAIR_ROWS = 2 if every phase's row count divides 32*16*2 else 1.
  I2P = [M, D, 2*INTER, D] / (32*16*PAIR_ROWS);  J2P = [K, DQ, K, INTER] / (2*256).
  GLU_SLICE = 1024 if (INTER/512) even else 512.  INTER padded up to a multiple of 512.
  vocab padded to a multiple of K;  N = Vpad/32/(16*PAIR_ROWS) = UNI_LM * VOCAB_CHUNK_I2,
  VOCAB_CHUNK_I2 = largest divisor of N that is <= 31 and makes (K/512) | VOCAB_CHUNK_I2*PAIR_ROWS.
  DECODE_WGROUP = layers per weight BO, ~<=1.15 GiB of Q4NX per BO (a shim BD offset is uint32).
"""
import json
import math
from dataclasses import dataclass, field

ROW_BLOCK, COL_BLOCK, N_PROJ_CORES, PAYLOAD = 32, 256, 16, 512
Q4NX_BYTES_PER_W = 0.625          # 4-bit + bf16 scale/offset per 32
WGROUP_TARGET = 1.15 * 2**30


class Unsupported(ValueError):
    """The shape needs an engine feature that does not exist yet (says which)."""


@dataclass
class DecodeSpec:
    name: str
    family: str
    K: int                      # model dim
    DQ: int
    DK: int
    INTER: int                  # padded
    INTER_REAL: int
    DH: int
    n_heads: int
    n_kv: int
    layers: int
    vocab: int
    rope_theta: float
    rms_eps: float
    qk_norm: bool
    qkv_bias: bool
    tied_head: bool
    act: str = "silu"
    entry: dict = field(default_factory=dict)   # the host driver's _MODELS entry

    def header(self, model_type_id):
        lines = [
            f"// generated by opennpu.native.specgen from {self.name} config.json -- do not edit",
            f"#ifndef __OPENNPU_{model_type_id}_H__", f"#define __OPENNPU_{model_type_id}_H__",
            f"#if MODEL_TYPE == {model_type_id}",
            f"constexpr int MODEL_DIM = {self.K};",
            f"constexpr int NUM_ATTN_HEADS = {self.n_heads};",
            f"constexpr int NUM_KV_HEADS = {self.n_kv};",
            f"constexpr int INTERMEDIATE_SIZE = {self.INTER};",
            f"constexpr int GLU_SLICE = {1024 if (self.INTER // 512) % 2 == 0 else 512};",
            f"constexpr int DH = {self.DH};",
            f"constexpr int VOCAB_SIZE = {self.vocab};",
            f"constexpr float ATTN_SCALE = {1 / math.sqrt(self.DH)!r}f;",
            f"#define ATTN_IMPL {self.entry['_ATTN_IMPL']}",
            f"#define A_FUNC {'A_SILU' if self.act == 'silu' else 'A_GELU'}",
        ]
        if self.qk_norm:
            lines.append("#define HAS_QK_NORM")
        if self.qkv_bias:
            lines.append("#define HAS_QKV_BIAS")
        if abs(self.rms_eps - 1e-6) > 1e-12:
            lines.append(f"#define RMS_NORM_EPS {self.rms_eps!r}f")
        lines += ["constexpr int Q4NX_ROW_BLOCK_SIZE = 32;", "constexpr int Q4NX_COL_BLOCK_SIZE = 256;",
                  "constexpr int Q4NX_GROUP_SIZE = 32;", "#endif", "#endif"]
        return "\n".join(lines) + "\n"

    def driver_entry(self):
        return {k: v for k, v in self.entry.items() if not k.startswith("_")}


def _round_up(x, a):
    return -(-x // a) * a


def from_hf_config(cfg: dict, name: str) -> DecodeSpec:
    mt = cfg.get("model_type", "")
    family = {"llama": "llama", "mistral": "llama", "qwen2": "qwen2", "qwen3": "qwen3"}.get(mt)
    if family is None:
        raise Unsupported(f"model_type {mt!r}: fused decode supports llama/mistral/qwen2/qwen3 dense today")
    if cfg.get("num_experts") or cfg.get("num_local_experts"):
        raise Unsupported("MoE: needs the expert-routing decode (roadmap)")
    act = cfg.get("hidden_act", "silu")
    if act not in ("silu", "swish"):
        raise Unsupported(f"activation {act!r}")
    K = cfg["hidden_size"]
    H = cfg["num_attention_heads"]
    KV = cfg.get("num_key_value_heads", H)
    DH = cfg.get("head_dim") or K // H
    DQ, DK = H * DH, KV * DH
    INTER_REAL = cfg["intermediate_size"]
    INTER = _round_up(INTER_REAL, 512)
    V = cfg["vocab_size"]
    L = cfg["num_hidden_layers"]
    if (cfg.get("rope_scaling") or {}).get("rope_type") not in (None, "default", "llama3", "linear"):
        raise Unsupported(f"rope_scaling {cfg['rope_scaling']}")
    if cfg.get("sliding_window") and cfg.get("use_sliding_window"):
        raise Unsupported("sliding-window attention")

    # attention mapping: up to 4 attention CUs, each holding KV_PER_CU kv heads; q heads per
    # kv group padded to a segment of 4 or 8. Only these three implementations exist.
    n_cu = min(4, KV)
    if KV % n_cu:
        raise Unsupported(f"{KV} kv heads do not split over {n_cu} attention CUs")
    kv_per_cu = KV // n_cu
    grp = H // KV
    seg = 4 if grp <= 4 else 8 if grp <= 8 else None
    impl = {(2, 4): "ATTN_IMPL_2x4x1", (1, 4): "ATTN_IMPL_1x4x1", (1, 8): "ATTN_IMPL_1x8x1",
            (2, 8): "ATTN_IMPL_2x8x1"}.get((kv_per_cu, seg))
    if impl is None:
        raise Unsupported(f"attention geometry kv_per_cu={kv_per_cu}, q-per-kv={grp} (seg {seg}) "
                          "has no kernel implementation (have 2x4x1, 1x4x1, 1x8x1, 2x8x1)")
    if DH not in (64, 128):
        raise Unsupported(f"head_dim {DH} (fused decode has 64/128; 256 is Gemma-only)")

    M = DQ + 2 * DK
    rows = [M, K, 2 * INTER, K]
    pair = 2 if all(r % (ROW_BLOCK * N_PROJ_CORES * 2) == 0 for r in rows) else 1
    unit = ROW_BLOCK * N_PROJ_CORES * pair
    if any(r % unit for r in rows):
        raise Unsupported(f"projection rows {rows} not multiples of {unit}")
    cols = [K, DQ, K, INTER]
    if any(c % (2 * COL_BLOCK) for c in cols):
        raise Unsupported(f"projection cols {cols} not multiples of {2 * COL_BLOCK}")
    i2p = [r // unit for r in rows]
    j2p = [c // (2 * COL_BLOCK) for c in cols]

    vpad = _round_up(V, K)
    n = vpad // ROW_BLOCK // (N_PROJ_CORES * pair)
    kp = K // PAYLOAD
    chunk = next((c for c in range(31, 0, -1) if n % c == 0 and (c * pair) % kp == 0), None)
    if chunk is None:
        raise Unsupported(f"no legal vocab chunk for vocab {V} at K={K}")

    per_layer = (M * K + K * DQ + 3 * INTER * K) * Q4NX_BYTES_PER_W
    wgroup = 0
    if per_layer * L > WGROUP_TARGET:
        wgroup = max(g for g in range(1, L + 1) if L % g == 0 and g * per_layer <= WGROUP_TARGET)

    entry = dict(
        K=K, M=M, DH_A=DH, KV_PER_CU=kv_per_cu, N_ATTN_CU=n_cu, NPH=4, I2P=i2p, J2P=j2p,
        DEST=["rope", "rms", "glu", "rms"], GQA_SEG=seg, PAIR_ROWS=pair, N_NORMS=2,
        HAS_QK_NORM=family == "qwen3", VOCAB_SIZE=V, UNI_DEC=L, UNI_LM=n // chunk, VOCAB_CHUNK_I2=chunk,
        _ATTN_IMPL=impl,
    )
    if family == "qwen2":
        entry["HAS_QKV_BIAS"] = True
        entry.pop("HAS_QK_NORM")
    if K >= 3584:
        entry["DECODE_STACK"] = 6144
    if wgroup:
        entry["DECODE_WGROUP"] = wgroup
    return DecodeSpec(
        name=name, family=family, K=K, DQ=DQ, DK=DK, INTER=INTER, INTER_REAL=INTER_REAL, DH=DH,
        n_heads=H, n_kv=KV, layers=L, vocab=V, rope_theta=float(cfg.get("rope_theta", 10000.0)),
        rms_eps=float(cfg.get("rms_norm_eps", 1e-6)), qk_norm=family == "qwen3", qkv_bias=family == "qwen2",
        tied_head=bool(cfg.get("tie_word_embeddings", False)), entry=entry)


def from_hf(repo_or_dir, name=None):
    import os
    if os.path.isdir(repo_or_dir):
        cfg = json.load(open(os.path.join(repo_or_dir, "config.json")))
    else:
        from huggingface_hub import hf_hub_download
        cfg = json.load(open(hf_hub_download(repo_or_dir, "config.json")))
    return from_hf_config(cfg, name or os.path.basename(repo_or_dir.rstrip("/")))
